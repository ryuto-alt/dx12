namespace dx12e
{

// 法線マップフィルタリング（specular anti-aliasing）の設定。
// SSAOSettings / ContactShadowSettings と同じ流儀のヘッダオンリー定義（シーン単位・シリアライズ対象）。
//
// ▼ 何を直すものか
//   高いタイリングの床/壁に法線マップを貼ると、1 画素の中に法線マップの山谷が何個も入り込む。
//   それを 1 サンプルで代表させると、
//     ① 鏡面がピクセル単位でちらつく（動かすと沸く）
//     ② 光源が面を舐める角度で N·L の符号が裏返り、面が黒い斑点で埋まる
//   の 2 つが起きる。本来は「画素内の法線分布の平均と分散」で陰影を出すべきなので、
//   分散をスクリーン空間の法線微分から見積もって
//     ① 分散を GGX のラフネス(α)へ足し込む（＝Toksvig / Kaplanyan の specular AA）
//     ② 分散が大きい画素は法線を幾何法線へ寄せる（＝平均法線の復元。黒斑点はこれで消える）
//   の 2 つを行う。
//
// ▼ なぜ実行時（シェーダ）でやるのか
//   法線マップは BC5_UNORM(RG 2ch) で読み込み、z は xy から再構成している。
//   ＝ミップ生成で平均した法線の「長さ（分散の情報）」がテクスチャに残らないので、
//   古典的な Toksvig 係数をミップに焼き込んでも実行時に読み出せない。
//   スクリーン空間微分ならタイリング倍率・視野角・距離を全部含んだ実効分散が取れる。
struct NormalFilterSettings
{
    bool  enabled        = true;    // 既定 ON（分散が小さい画素では恒等なので副作用はほぼ無い）
    float strength       = 2.0f;    // 分散のスケール。0 で OFF と同じ
    float varianceClamp  = 0.25f;   // ラフネス α に足せる量の上限（大きいほどボケる）
    float geometricBlend = 2.0f;    // 分散に応じて幾何法線へ寄せる強さ。0 でラフネス補正のみ
};

} // namespace dx12e
